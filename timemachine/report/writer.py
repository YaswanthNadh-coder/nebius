"""Report generation, SQL transaction wrapping, and multi-format migration exporters."""

from datetime import datetime

from timemachine.agent.loop import AgentRunResult
from timemachine.verify.spec import MigrationSpec


def wrap_transaction_with_prechecks(
    sql: str,
    target_table: str,
    spec: MigrationSpec | None = None,
) -> str:
    """Wrap SQLite migration script in a transaction with pre-conditions and post-checks."""
    lines = [
        "-- ========================================================",
        "-- SQL MIGRATION DRY-RUN TIME MACHINE - GENERATED MIGRATION",
        f"-- Generated at: {datetime.now().isoformat()}",
        f"-- Target Table: {target_table}",
        "-- ========================================================",
        "",
        "PRAGMA foreign_keys = OFF;",
        "BEGIN TRANSACTION;",
        "",
        "-- PRE-CHECK: Ensure target table exists",
        f"SELECT CASE WHEN (SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND name='{target_table}') = 0",
        f"  THEN RAISE(ABORT, 'Target table {target_table} does not exist!') END;",
        "",
        "-- MIGRATION DDL / DML STATEMENTS",
        sql.strip(),
        "",
        "-- POST-CHECK: Integrity and Foreign Key Verifications",
        "PRAGMA foreign_key_check;",
        "",
        "COMMIT;",
        "PRAGMA foreign_keys = ON;",
        "",
    ]
    return "\n".join(lines)


def export_plain_sql(up_sql: str, down_sql: str) -> dict[str, str]:
    """Export standard up.sql and down.sql files."""
    return {
        "up.sql": up_sql,
        "down.sql": down_sql,
    }


def export_flyway(up_sql: str, down_sql: str, version: str = "1") -> dict[str, str]:
    """Export Flyway versioned migration and undo migration."""
    return {
        f"V{version}__migration.sql": up_sql,
        f"U{version}__migration.sql": down_sql,
    }


def export_alembic(up_sql: str, down_sql: str, revision_id: str = "tm_001") -> str:
    """Export Alembic migration script template."""
    return f'''"""Alembic migration generated by SQL Migration Time Machine.

Revision ID: {revision_id}
Revises: None
Create Date: {datetime.now().isoformat()}

"""
from alembic import op
import sqlalchemy as sa

# revision identifiers, used by Alembic.
revision = '{revision_id}'
down_revision = None
branch_labels = None
depends_on = None


def upgrade() -> None:
    # Execute verified forward migration
    op.execute("""
{up_sql}
    """)


def downgrade() -> None:
    # Execute verified rollback migration
    op.execute("""
{down_sql}
    """)
'''


def generate_markdown_report(result: AgentRunResult, target_table: str, goal: str) -> str:
    """Generate comprehensive GitHub-flavored markdown audit report."""
    inv = result.invariant_result
    status_badge = "VERIFIED" if result.status == "VERIFIED" else ("UNVERIFIED" if result.status == "UNVERIFIED" else "FAILED")

    passed_checks_md = "\n".join([f"- [x] {c}" for c in (inv.passed_checks if inv else [])]) or "None"
    failed_checks_md = "\n".join([f"- [ ] **FAILED**: {c}" for c in (inv.failed_checks if inv else [])]) or "None"

    # Trap matrix
    trap_lines = []
    if inv and inv.trap_audit:
        for t in inv.trap_audit:
            icon = "[x]" if t.get("survived") else "[ ] **SURVIVED FAILED**"
            trap_lines.append(f"- {icon} Trap `{t.get('trap_type')}`: {t.get('description')} (Row ID: {t.get('pk')})")
    trap_md = "\n".join(trap_lines) if trap_lines else "No adversarial trap tests recorded."

    # Lock info
    lock = result.lock_estimate
    lock_md = f"Estimated Production Lock Duration: **{lock.get('estimated_lock_sec', 0.0)}s** ({lock.get('risk_level', 'LOW')} Risk)"
    if lock.get("warning"):
        lock_md += f"\n> Warning: {lock['warning']}"

    rollback_status = "Roundtrip Verified (Zero loss)" if result.rollback_verified else f"Not Verified ({result.rollback_error or 'None'})"
    if result.lossy_columns:
        rollback_status += f" (Lossy columns: {', '.join(result.lossy_columns)})"

    md = f"""# SQL Migration Verification Report

**Target Table:** `{target_table}`
**Status:** **{status_badge}**
**Migration Goal:** {goal}
**Total Steps:** {len(result.steps)} | **Total Latency:** {round(result.total_latency_ms / 1000, 2)}s

---

## 1. Executive Summary & Verification Matrix

| Metric | Value |
|---|---|
| **Verification Level** | `{result.status}` |
| **Rows Baseline** | {inv.before_count if inv else 'N/A'} |
| **Rows After Migration** | {inv.after_count if inv else 'N/A'} |
| **Rollback Status** | {rollback_status} |
| **Lock Risk** | {lock.get('risk_level', 'LOW')} ({lock.get('estimated_lock_sec', 0.0)}s) |

---

## 2. Invariants Audit Log

### Passed Invariants
{passed_checks_md}

### Failed Invariants / Anomalies
{failed_checks_md}

---

## 3. Adversarial Edge-Case Traps
{trap_md}

---

## 4. Production Lock & Risk Extrapolation
{lock_md}

---

## 5. Agent Steps & Reasoning Trace
"""
    for s in result.steps:
        md += f"- **Step {s.step}** [{s.model}] `{s.action}` ({round(s.latency_ms)}ms) - Status: {s.status}\n"

    return md
